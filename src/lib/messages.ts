/** Arabic count words: 1 أداة واحدة, 2 أداتان, 3–10 أدوات, 11+ أداة. */
export function arCount(n: number, one: string, two: string, few: string, many: string): string {
  if (n === 1) return one;
  if (n === 2) return two;
  const mod = n % 100;
  if (mod >= 3 && mod <= 10) return `${n} ${few}`;
  return `${n} ${many}`;
}

