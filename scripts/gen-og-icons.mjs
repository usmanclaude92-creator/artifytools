// Writes src/lib/og-icons.ts: the SVG markup of every icon in src/components/ui/icon.tsx, for share images.
// Share images are rendered on the server, where lucide-react's client components can't be called.
// Run after adding an icon: node scripts/gen-og-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import * as lucide from "lucide-react";

const src = readFileSync(new URL("../src/components/ui/icon.tsx", import.meta.url), "utf8");
const map = src.slice(src.indexOf("const icons = {"), src.indexOf("};", src.indexOf("const icons = {")));
const entries = [...map.matchAll(/^\s+"?([a-z0-9-]+)"?: (\w+),/gm)].map((m) => [m[1], m[2]]);
const out = {};
for (const [name, comp] of entries) {
  const C = lucide[comp];
  if (!C) throw new Error(`missing ${comp}`);
  out[name] = renderToStaticMarkup(createElement(C, { size: 24, strokeWidth: 1.8, color: "COLOR" }));
}
writeFileSync(
  new URL("../src/lib/og-icons.ts", import.meta.url),
  `// Generated by scripts/gen-og-icons.mjs. Do not edit.\nimport type { IconName } from "@/components/ui/icon";\n\nexport const ogIcons: Record<IconName, string> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(entries.length, "icons");
